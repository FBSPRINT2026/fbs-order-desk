const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
export type LibItem<T> = T & { id: string };
const withIds = <T extends { name: string }>(kind: string, xs: T[]): LibItem<T>[] => xs.map((x) => ({ ...x, id: `${kind}:${slug(x.name)}` }));

